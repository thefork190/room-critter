"""Original Room Critter low-poly axolotl-like buddy. Deterministic; stdlib only."""
import math, struct, zlib
from pathlib import Path
root=Path(__file__).resolve().parents[1]
verts=[];norms=[];uvs=[];faces=[]
colors=[(92,220,179),(244,175,200),(25,45,55),(255,255,245)]
def ellipsoid(center,radii,color):
    first=len(verts)
    for y in range(9):
        phi=math.pi*y/8
        for x in range(13):
            theta=2*math.pi*x/12
            n=(math.sin(phi)*math.cos(theta),math.cos(phi),math.sin(phi)*math.sin(theta))
            verts.append(tuple(center[i]+n[i]*radii[i] for i in range(3)))
            norm=tuple(n[i]/radii[i] for i in range(3));l=math.sqrt(sum(v*v for v in norm))
            norms.append(tuple(v/l for v in norm));uvs.append(((color+.5)/4,.5))
    for y in range(8):
        for x in range(12):
            a=first+y*13+x;b=a+13
            for tri in [(a,b,a+1),(a+1,b,b+1)]:
                v0,v1,v2=[verts[i] for i in tri]
                u=[v1[i]-v0[i] for i in range(3)];v=[v2[i]-v0[i] for i in range(3)]
                cross=(u[1]*v[2]-u[2]*v[1],u[2]*v[0]-u[0]*v[2],u[0]*v[1]-u[1]*v[0])
                if sum(c*c for c in cross)<1e-16:continue
                if sum(cross[i]*(v0[i]-center[i]) for i in range(3))<0:tri=tri[::-1]
                faces.append(tri)
ellipsoid((0,.10,0),(.095,.08,.13),0)
ellipsoid((0,.17,.09),(.115,.085,.085),0)
for side in [-1,1]:
    for z in [-.07,.075]:ellipsoid((side*.075,.025,z),(.035,.025,.045),1)
    ellipsoid((side*.045,.19,.162),(.018,.021,.012),2)
    ellipsoid((side*.041,.198,.172),(.006,.007,.004),3)
    for y in [.15,.19,.23]:ellipsoid((side*.122,y,.08),(.036,.012,.018),1)
ellipsoid((0,.07,-.145),(.04,.03,.08),1)
lines=['# Original procedural Room Critter mesh; generated by tools/generate_critter.py']
lines += ['v '+' '.join(f'{v:.6f}' for v in row) for row in verts]
lines += ['vt '+' '.join(f'{v:.6f}' for v in row) for row in uvs]
lines += ['vn '+' '.join(f'{v:.6f}' for v in row) for row in norms]
lines += ['f '+' '.join(f'{i+1}/{i+1}/{i+1}' for i in face) for face in faces]
assets=root/'app/src/main/assets/models';(assets/'critter.obj').write_text('\n'.join(lines)+'\n')
def chunk(t,data):return struct.pack('!I',len(data))+t+data+struct.pack('!I',zlib.crc32(t+data)&0xffffffff)
# 64x16 nearest-color bands; enough separation for mipmapping.
raw=b''.join(b'\0'+b''.join(bytes(colors[x//16]) for x in range(64)) for y in range(16))
png=b'\x89PNG\r\n\x1a\n'+chunk(b'IHDR',struct.pack('!2I5B',64,16,8,2,0,0,0))+chunk(b'IDAT',zlib.compress(raw))+chunk(b'IEND',b'')
(assets/'critter.png').write_bytes(png)
print(f'{len(verts)} vertices; {len(faces)} triangles')
